// bake_font: turn a TTF into a C++ header of 8-bit alpha glyphs (printable ASCII).
//
//   bake_font <font.ttf> <em px> <identifier> <out.h>
//
// The output defines gfx::fonts::<identifier> (a gfx::FontFace) and its tables.
// Digits share one advance (the widest digit), so minutes do not shift when the
// digit changes. Kerning comes from the legacy 'kern' table only (stb_truetype
// does not read GPOS); if the font has none, the kern table is omitted.
//
// Build:  g++ -std=c++17 -O2 -o bake_font tools/bake_font.cpp

#define STB_TRUETYPE_IMPLEMENTATION
#include "../third_party/stb_truetype.h"

#include <cmath>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <string>
#include <vector>

namespace {

constexpr int kFirst = 32, kLast = 126, kCount = kLast - kFirst + 1;

[[noreturn]] void die(const char* msg) {
    std::fprintf(stderr, "bake_font: %s\n", msg);
    std::exit(1);
}

std::vector<unsigned char> readFile(const char* path) {
    FILE* f = std::fopen(path, "rb");
    if (!f) die("cannot open font");
    std::vector<unsigned char> data;
    unsigned char buf[65536];
    size_t n;
    while ((n = std::fread(buf, 1, sizeof buf, f)) > 0) data.insert(data.end(), buf, buf + n);
    std::fclose(f);
    return data;
}

}  // namespace

int main(int argc, char** argv) {
    if (argc != 5) die("usage: bake_font <font.ttf> <em px> <identifier> <out.h>");
    const char* ttf = argv[1];
    const float px = static_cast<float>(std::atof(argv[2]));
    const std::string ident = argv[3];
    const char* outPath = argv[4];
    if (px < 8 || px > 96) die("em px out of range");

    std::vector<unsigned char> data = readFile(ttf);
    stbtt_fontinfo info;
    if (!stbtt_InitFont(&info, data.data(), stbtt_GetFontOffsetForIndex(data.data(), 0)))
        die("not a usable TTF");

    const float scale = stbtt_ScaleForPixelHeight(&info, px);
    int asc = 0, desc = 0, gap = 0;
    stbtt_GetFontVMetrics(&info, &asc, &desc, &gap);

    // Digit advance: the widest digit, shared by all digits.
    int digitAdv = 0;
    for (char d = '0'; d <= '9'; ++d) {
        int adv, lsb;
        stbtt_GetCodepointHMetrics(&info, d, &adv, &lsb);
        digitAdv = std::max(digitAdv, static_cast<int>(std::lround(adv * scale)));
    }

    struct G { int w, h, xoff, yoff, adv; uint32_t off; };
    std::vector<G> glyphs(kCount);
    std::vector<uint8_t> alpha;

    for (int cp = kFirst; cp <= kLast; ++cp) {
        G& g = glyphs[cp - kFirst];
        int adv, lsb;
        stbtt_GetCodepointHMetrics(&info, cp, &adv, &lsb);
        int advPx = static_cast<int>(std::lround(adv * scale));
        int w = 0, h = 0, xo = 0, yo = 0;
        unsigned char* bm = stbtt_GetCodepointBitmap(&info, scale, scale, cp, &w, &h, &xo, &yo);
        g.off = static_cast<uint32_t>(alpha.size());
        if (bm && w > 0 && h > 0) {
            alpha.insert(alpha.end(), bm, bm + w * h);
        }
        if (bm) stbtt_FreeBitmap(bm, nullptr);
        if (w > 255 || h > 255) die("glyph bitmap too large");
        if (cp >= '0' && cp <= '9') {
            xo += (digitAdv - advPx) / 2;  // centre the digit in the shared advance
            advPx = digitAdv;
        }
        if (xo < -128 || xo > 127 || yo < -128 || yo > 127) die("glyph offset out of int8 range");
        if (advPx < 0 || advPx > 255) die("advance out of range");
        g = G{w, h, xo, yo, advPx, g.off};
    }

    // Kerning, in px, only for pairs that are not zero.
    std::vector<int> kern(kCount * kCount, 0);
    bool anyKern = false;
    for (int a = kFirst; a <= kLast; ++a)
        for (int b = kFirst; b <= kLast; ++b) {
            int k = stbtt_GetCodepointKernAdvance(&info, a, b);
            if (!k) continue;
            int kp = static_cast<int>(std::lround(k * scale));
            if (kp < -128 || kp > 127) die("kern value out of int8 range");
            kern[(a - kFirst) * kCount + (b - kFirst)] = kp;
            if (kp) anyKern = true;
        }
    if (!anyKern) std::fprintf(stderr, "bake_font: %s has no kern pairs, omitting kern table\n", ttf);

    int ascPx = static_cast<int>(std::lround(asc * scale));
    int descPx = static_cast<int>(std::lround(-desc * scale));

    FILE* out = std::fopen(outPath, "w");
    if (!out) die("cannot write output");
    std::fprintf(out,
        "// Generated by tools/bake_font.cpp from %s at %g px. Do not edit.\n"
        "// Font licence: see third_party/fonts/NOTICE.\n"
        "#pragma once\n"
        "#include \"../text.h\"\n\n"
        "namespace gfx::fonts {\n\n",
        ttf, px);

    std::fprintf(out, "inline constexpr Glyph %s_glyphs[%d] = {\n", ident.c_str(), kCount);
    for (const G& g : glyphs)
        std::fprintf(out, "  {%d, %d, %d, %d, %d, %uu},\n", g.w, g.h, g.xoff, g.yoff, g.adv, g.off);
    std::fprintf(out, "};\n\n");

    std::fprintf(out, "inline constexpr uint8_t %s_alpha[%zu] = {", ident.c_str(),
                 alpha.empty() ? size_t(1) : alpha.size());
    if (alpha.empty()) std::fprintf(out, "0");
    for (size_t i = 0; i < alpha.size(); ++i)
        std::fprintf(out, "%s%u,", (i % 24 == 0) ? "\n  " : "", alpha[i]);
    std::fprintf(out, "\n};\n\n");

    if (anyKern) {
        std::fprintf(out, "inline constexpr int8_t %s_kern[%d] = {", ident.c_str(), kCount * kCount);
        for (int i = 0; i < kCount * kCount; ++i)
            std::fprintf(out, "%s%d,", (i % 24 == 0) ? "\n  " : "", kern[i]);
        std::fprintf(out, "\n};\n\n");
    }

    std::fprintf(out,
        "inline constexpr FontFace %s = {\n"
        "  %s_glyphs, %s_alpha, %s, %d, %d, %d,\n"
        "};\n\n"
        "}  // namespace gfx::fonts\n",
        ident.c_str(), ident.c_str(), ident.c_str(),
        anyKern ? (ident + "_kern").c_str() : "nullptr", ascPx, descPx,
        static_cast<int>(std::lround(px)));
    std::fclose(out);
    return 0;
}
